
import { promises as fs } from 'fs';
import path from 'path';

const projectRoot = '/Users/doudoufei/WorkSpace/WebstormProjects/mcp-chrome';
const injectScriptsDir = path.join(projectRoot, 'app/chrome-extension/inject-scripts');
const outputDir = path.join(projectRoot, 'app/chrome-extension/utils');
const outputFile = path.join(outputDir, 'dom-helpers.generated.ts');

// 定义需要处理的脚本及其相关信息
const SCRIPTS_TO_PROCESS = [
  {
    fileName: 'click-helper.js',
    isIIFE: false,
  },
  {
    fileName: 'fill-helper.js',
    isIIFE: false,
  },
  {
    fileName: 'interactive-elements-helper.js',
    isIIFE: true,
  },
  {
    fileName: 'keyboard-helper.js',
    isIIFE: false,
  },
  {
    fileName: 'network-helper.js',
    isIIFE: false,
  },
  {
    fileName: 'screenshot-helper.js',
    isIIFE: false,
  },
  {
    fileName: 'web-fetcher-helper.js',
    isIIFE: false,
  },
];

async function main() {
  let allCleanedCode = `/* eslint-disable */
// This file is auto-generated by scripts/prepare-dom-helpers.mjs. Do not edit manually.

`;

  for (const script of SCRIPTS_TO_PROCESS) {
    const filePath = path.join(injectScriptsDir, script.fileName);
    try {
      const fileContent = await fs.readFile(filePath, 'utf-8');
      
      // 1. 移除 chrome.runtime.onMessage 监听器
      let cleanedContent = fileContent.replace(
        /chrome\.runtime\.onMessage\.addListener\([\s\S]*?\);/gm,
        ''
      );

      // 2. 移除 IIFE 包装 (如果存在)
      if (script.isIIFE) {
        cleanedContent = cleanedContent
          .replace(/^\s*\(\s*function\s*\(\)\s*\{/m, '')
          .replace(/\}\s*\)\s*\(\s*\);?\s*$/m, '');
      }
      
      // 3. 移除初始化检查的 if/else 包装
      cleanedContent = cleanedContent.replace(/if\s*\(window\.__[A-Z_]+_INITIALIZED__\)\s*\{[\s\S]*?\}\s*else\s*\{/m, '');
      // 移除多余的右括号
      cleanedContent = cleanedContent.trim().slice(0, -1);

      // 4. 将函数声明转换为导出的函数表达式
      cleanedContent = cleanedContent.replace(/async function\s+([a-zA-Z0-9_]+)/g, 'export const $1 = async function');
      cleanedContent = cleanedContent.replace(/function\s+([a-zA-Z0-9_]+)/g, 'export const $1 = function');

      allCleanedCode += `// --- From ${script.fileName} ---
${cleanedContent}

`;

    } catch (error) {
      console.error(`Error processing ${script.fileName}:`, error);
    }
  }

  try {
    await fs.mkdir(outputDir, { recursive: true });
    await fs.writeFile(outputFile, allCleanedCode, 'utf-8');
    console.log(`Successfully generated ${outputFile}`);
  } catch (error) {
    console.error(`Error writing output file:`, error);
  }
}

main();
